"""Create #ui and #devops channels (idempotent — skips if exist) and seed
each w/ realistic team-convention messages. Run alongside the existing
slack_seed.py for #backend + #ds.
"""
from __future__ import annotations

import json
import os
import sys
import time
import urllib.request
from pathlib import Path

env = Path(__file__).resolve().parent.parent / ".env"
if env.exists():
    for line in env.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        os.environ.setdefault(k.strip(), v.strip())

TOKEN = os.environ["SLACK_BOT_TOKEN"]


def call(method: str, body: dict) -> dict:
    req = urllib.request.Request(
        f"https://slack.com/api/{method}",
        data=json.dumps(body).encode(),
        headers={
            "Authorization": f"Bearer {TOKEN}",
            "Content-Type": "application/json; charset=utf-8",
        },
    )
    with urllib.request.urlopen(req, timeout=15) as resp:
        return json.loads(resp.read())


def list_channels() -> dict[str, str]:
    """Return {channel_name: channel_id} for public channels."""
    out: dict[str, str] = {}
    cursor = ""
    while True:
        body = {"types": "public_channel", "limit": 200}
        if cursor:
            body["cursor"] = cursor
        r = call("conversations.list", body)
        for c in r.get("channels", []):
            out[c["name"]] = c["id"]
        cursor = r.get("response_metadata", {}).get("next_cursor", "")
        if not cursor:
            break
    return out


def ensure_channel(name: str, existing: dict[str, str]) -> str:
    if name in existing:
        print(f"  exists: #{name} -> {existing[name]}")
        return existing[name]
    r = call("conversations.create", {"name": name, "is_private": False})
    if not r.get("ok"):
        raise RuntimeError(f"create #{name} failed: {r}")
    cid = r["channel"]["id"]
    print(f"  created: #{name} -> {cid}")
    return cid


def post(channel_id: str, text: str) -> None:
    r = call("chat.postMessage", {"channel": channel_id, "text": text})
    if not r.get("ok"):
        print(f"   post err: {r.get('error')}")



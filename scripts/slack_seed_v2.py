def main() -> int:
    print("Listing existing channels...")
    existing = list_channels()
    print()

    ui_id = ensure_channel("ui", existing)
    devops_id = ensure_channel("devops", existing)
    print()

    print(f"Seeding #ui ({ui_id}) w/ {len(UI_MSGS)} messages")
    for m in UI_MSGS:
        post(ui_id, m)
        time.sleep(0.3)

    print(f"Seeding #devops ({devops_id}) w/ {len(DEVOPS_MSGS)} messages")
    for m in DEVOPS_MSGS:
        post(devops_id, m)
        time.sleep(0.3)

    print("OK")
    print()
    print("Channels for .env / agent config:")
    print(f"  SLACK_CHANNEL_UI={ui_id}")
    print(f"  SLACK_CHANNEL_DEVOPS={devops_id}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
